export function usePublicUxCopy() {
  return copy[useLanguage().locale];
}

export default function PublicUxText({ id }: { id: keyof typeof copy.it }) {
  return usePublicUxCopy()[id];
}

export function PublicEventDateRange({
  startsAt,
  endsAt,
  timeZone,
}: {
  startsAt: string;
  endsAt: string;
  timeZone: string;
}) {
  const { locale } = useLanguage();
  return (
    <>
      <LocalDateTime value={startsAt} format="datetime-weekday" timeZone={timeZone} locale={locale} />
      {" – "}
      <LocalDateTime value={endsAt} format="datetime-weekday" timeZone={timeZone} locale={locale} />
    </>
  );
}
